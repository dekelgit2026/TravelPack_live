"""Build prototype/eval-data.js: everything the Eval tab needs to run in the browser. Contains NO secrets.

    python evalkit/build_site_data.py travel

Packs: the prompt versions (with the policy attached, exactly as the model sees them), the output schema, the runnable
cases, every recorded run in results/<pack>/ (real outputs, tokens, cost, latency), the scoreboard and the price table.
Re-run it after a new /score so the page shows the latest evidence.
"""
from __future__ import annotations

import csv
import glob
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from evalkit import run_eval as R  # noqa: E402

CORRECTED_FROM = "20261113-231800"  # runs at or after this stamp used the corrected cases.csv checks


def main(pack: str) -> None:
    root = R.ROOT
    versions = sorted(re.findall(r"system_(v\d+)\.md$", p.name)[0] for p in (root / "prompts" / pack).glob("system_v*.md"))
    prompts = {v: R.read_prompt(pack, v)[0] for v in versions}
    with (root / "prompts" / pack / "cases.csv").open(encoding="utf-8-sig", newline="") as f:
        cases = [{"id": r["id"], "input": r["input"], "checks": r["checks"],
                  "critical": r["critical"].strip().lower() in ("yes", "y", "true", "1"),
                  "layer": r.get("layer", "")} for r in csv.DictReader(f) if r.get("id")]
    runs = []
    for fp in sorted((root / "results" / pack).glob("*.json")):
        rep = json.loads(fp.read_text(encoding="utf-8"))
        stamp = fp.name[:15]
        runs.append({
            "file": fp.name, "stamp": stamp, "ran_at": rep["ran_at"], "engine": rep["engine"],
            "prompt": rep["prompt"], "model": rep["model"], "passed": rep["passed"], "cases": rep["cases"],
            "score_pct": rep["score_pct"], "critical_failed": rep["critical_failed"],
            "cost_per_case_usd": rep["cost_per_case_usd"], "latency_ms_median": rep["latency_ms_median"],
            "cache_read_pct": rep["cache_read_pct"], "checks": "corrected" if stamp >= CORRECTED_FROM else "first",
            "results": [{k: x.get(k) for k in ("id", "passed", "output", "cost_usd", "latency_ms", "input_tokens",
                                               "output_tokens", "cache_read", "cache_write")} for x in rep["results"]],
        })
    data = {
        "pack": pack, "volume_per_month": 260, "bar": 80, "prices": R.load_prices(), "versions": versions,
        "prompts": prompts, "schema": R.read_schema(pack), "cases": cases,
        "baseline": json.loads((root / "prompts" / pack / "baseline.json").read_text(encoding="utf-8")),
        "runs": runs,
        "approved": None,
    }
    ap = root / "prompts" / pack / "approved_baseline.json"
    if ap.exists():  # the approved baseline: a version + model run the team signed off (set in the Eval lab)
        data["approved"] = json.loads(ap.read_text(encoding="utf-8"))
    out = root / "prototype" / "eval-data.js"
    out.write_text("/* generated by evalkit/build_site_data.py: no secrets */\nwindow.EVALDATA = "
                   + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(root)}: {len(versions)} prompt versions, {len(cases)} cases, {len(runs)} recorded runs, "
          f"{out.stat().st_size // 1024} KB")


def _inline(t: str) -> str:
    import html
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"<i>\1</i>", t)
    return (t.replace("OPEN QUESTION", '<span class="pv-tg pv-q">OPEN QUESTION</span>')
             .replace("ASSUMPTIONS", '<span class="pv-tg pv-a">ASSUMPTIONS</span>')
             .replace("ASSUMPTION", '<span class="pv-tg pv-a">ASSUMPTION</span>'))


def _md(src: str) -> str:
    """A small markdown renderer for the spec and the card: headings, lists, tables, bold, code."""
    out, lines, i, lst = [], src.replace("\r\n", "\n").split("\n"), 0, None

    def close():
        nonlocal lst
        if lst:
            out.append(f"</{lst}>")
            lst = None
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("|"):
            close()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            rows = [r for r in rows if not all(re.fullmatch(r":?-+:?", c) for c in r)]
            out.append("<div class='pv-tw'><table><thead><tr>" + "".join(f"<th>{_inline(c)}</th>" for c in rows[0]) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in r) + "</tr>" for r in rows[1:]) + "</tbody></table></div>")
            continue
        m = re.match(r"^(#{1,3}) (.*)", ln)
        if m:
            close()
            out.append(f"<h{len(m.group(1))}>{_inline(m.group(2))}</h{len(m.group(1))}>")
        elif ln.startswith("- "):
            if lst != "ul":
                close(); out.append("<ul>"); lst = "ul"
            out.append(f"<li>{_inline(ln[2:])}</li>")
        elif re.match(r"^\d+\. ", ln):
            if lst != "ol":
                close(); out.append("<ol>"); lst = "ol"
            out.append(f"<li>{_inline(re.sub(r'^\d+\. ', '', ln))}</li>")
        elif ln.strip() == "":
            close()
        else:
            close(); out.append(f"<p>{_inline(ln)}</p>")
        i += 1
    close()
    return "\n".join(out)


def build_private() -> None:
    """prototype/private-data.js: the private-trip spec and card, rendered for the page (skipped if the pack is absent)."""
    root = R.ROOT
    spec, card = root / "designs" / "private-trip" / "spec.md", root / "packs" / "private-trip" / "opportunity.md"
    if not (spec.exists() and card.exists()):
        print("private trip: no pack found, skipped")
        return
    s = spec.read_text(encoding="utf-8")
    m = re.search(r"OPEN QUESTIONS:\n(.*?)\n\nASSUMPTIONS", s, re.S)
    open_q = [re.sub(r"^\d+\.\s*", "", x).strip() for x in (m.group(1).split("\n") if m else []) if x.strip()]
    data = {"specHtml": _md(s), "cardHtml": _md(card.read_text(encoding="utf-8")), "open": open_q}
    out = root / "prototype" / "private-data.js"
    out.write_text("/* generated by evalkit/build_site_data.py: no secrets */\nwindow.PRVDATA = " + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(root)}: spec {len(data['specHtml']) // 1024} KB, {len(open_q)} open questions")


def build_site() -> None:
    """Copy the page and its data into docs/ for GitHub Pages (Settings > Pages > main branch, /docs)."""
    import shutil
    root = R.ROOT
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    shutil.copyfile(root / "prototype" / "trip-planner.html", docs / "index.html")
    shutil.copyfile(root / "prototype" / "eval-data.js", docs / "eval-data.js")
    if (root / "prototype" / "private-data.js").exists():
        shutil.copyfile(root / "prototype" / "private-data.js", docs / "private-data.js")
    (docs / ".nojekyll").write_text("", encoding="utf-8")
    print("site: docs/index.html, docs/eval-data.js, docs/.nojekyll (no secrets; the page has no key and no server)")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    main(args[0] if args else "travel")
    build_private()
    if "--site" in sys.argv:
        build_site()
